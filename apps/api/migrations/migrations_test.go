const bootstrap = "docker compose up -d db   # or any PostgreSQL 16"

func openSchema(t *testing.T, prefix string, prepare func(*gorm.DB) error) *gorm.DB {
	t.Helper()
	url, ok := testdb.URL()
	if !ok {
		testdb.Announce(bootstrap)
		t.Skip(testdb.SkipReason(bootstrap))
	}
	admin, err := testdb.Open(url, testdb.Config{Prefix: prefix + "_admin", Migrate: func(*gorm.DB) error { return nil }})
	if err != nil {
		t.Fatalf("open: %v", err)
	}
	if err := admin.Exec(`DROP SCHEMA IF EXISTS "` + testdb.SchemaName(prefix) + `" CASCADE`).Error; err != nil {
		t.Fatalf("drop the previous run's schema: %v", err)
	}
	db, err := testdb.Open(url, testdb.Config{Prefix: prefix, Migrate: prepare})
	if err != nil {
		t.Fatalf("open %s: %v", prefix, err)
	}
	return db
}

func runUp(db *gorm.DB) error {
	sqlDB, err := db.DB()
	if err != nil {
		return err
	}
	return Up(context.Background(), Config(sqlDB, nil))
}

func appliedVersions(t *testing.T, db *gorm.DB) []int64 {
	t.Helper()
	var versions []int64
	if err := db.Raw(`SELECT version_id FROM goose_db_version WHERE version_id > 0 ORDER BY id`).Scan(&versions).Error; err != nil {
		t.Fatalf("read the ledger: %v", err)
	}
	return versions
}

func columnDefault(t *testing.T, db *gorm.DB, table, column string) string {
	t.Helper()
	var value *string
	err := db.Raw(`SELECT column_default FROM information_schema.columns
		WHERE table_schema = current_schema() AND table_name = ? AND column_name = ?`, table, column).Scan(&value).Error
	if err != nil {
		t.Fatalf("read the default of %s.%s: %v", table, column, err)
	}
	if value == nil {
		return ""
	}
	return *value
}

func baselineUp(t *testing.T) string {
	t.Helper()
	raw, err := fs.ReadFile(FS, "00001_baseline.sql")
	if err != nil {
		t.Fatalf("read the baseline: %v", err)
	}
	up, _, found := strings.Cut(strings.SplitN(string(raw), "-- +goose Up", 2)[1], "-- +goose Down")
	if !found {
		t.Fatal("the baseline has no Down section")
	}
	return up
}

// TestUpBuildsAnEmptyDatabase checks an empty schema reaches the latest
// version through every migration in order.
func TestUpBuildsAnEmptyDatabase(t *testing.T) {
	db := openSchema(t, "agenda_migrations_fresh", runUp)
	if got := appliedVersions(t, db); !slices.Equal(got, []int64{1, 2, 3}) {
		t.Fatalf("applied versions %v, want [1 2 3]", got)
	}
	if got := columnDefault(t, db, "users", "created_at"); got != "now()" {
		t.Fatalf("users.created_at default %q, want now()", got)
	}
	if err := runUp(db); err != nil {
		t.Fatalf("a second run is not a no-op: %v", err)
	}
}

// TestUpStampsADatabaseBuiltByAutoMigrate rebuilds production's shape, the
// baseline's tables with no ledger and a row in them, and checks Up records
// the baseline without running it, applies the later migrations, and keeps
// the row. Running the baseline would fail on its first CREATE TABLE.
func TestUpStampsADatabaseBuiltByAutoMigrate(t *testing.T) {
	assertStampsLegacy(t, "agenda_migrations_legacy", "")
}

// TestUpStampsALegacyDatabaseAfterStatus covers an operator who ran
// `migrate status` before the first boot: goose then created the ledger with
// only its version 0 sentinel, and the baseline must still be stamped rather
// than run.
func TestUpStampsALegacyDatabaseAfterStatus(t *testing.T) {
	assertStampsLegacy(t, "agenda_migrations_status",
		`CREATE TABLE goose_db_version (id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
			version_id bigint NOT NULL, is_applied boolean NOT NULL, tstamp timestamp NOT NULL DEFAULT now());
		 INSERT INTO goose_db_version (version_id, is_applied) VALUES (0, true);`)
}

func assertStampsLegacy(t *testing.T, prefix, ledger string) {
	t.Helper()
	up := baselineUp(t)
	db := openSchema(t, prefix, func(db *gorm.DB) error {
		if ledger != "" {
			if err := db.Exec(ledger).Error; err != nil {
				return err
			}
		}
		if err := db.Exec(up).Error; err != nil {
			return err
		}
		return db.Exec(`INSERT INTO users (email, name, locale, created_at) VALUES ('ada@facile.studio', 'Ada', 'fr', '2026-01-02T03:04:05Z')`).Error
	})
	if columnDefault(t, db, "users", "created_at") != "" {
		t.Fatal("the legacy schema already has the defaults migration")
	}

	if err := runUp(db); err != nil {
		t.Fatalf("up on a legacy database: %v", err)
	}
	if got := appliedVersions(t, db); !slices.Equal(got, []int64{1, 2, 3}) {
		t.Fatalf("applied versions %v, want the stamped baseline then 2 and 3", got)
	}
	if got := columnDefault(t, db, "users", "created_at"); got != "now()" {
		t.Fatalf("users.created_at default %q, want now()", got)
	}
	var kept struct {
		Name   string
		Locale string
	}
	if err := db.Raw(`SELECT name, locale FROM users WHERE email = 'ada@facile.studio'`).Scan(&kept).Error; err != nil {
		t.Fatalf("read the row: %v", err)
	}
	if kept.Name != "Ada" || kept.Locale != "fr" {
		t.Fatalf("the existing row changed: %+v", kept)
	}
}

// TestOutboxMigrationIsTheLibrarys checks 00003 is antenne-client's outbox
// migration byte for byte, so the table is the one the drainer queries.
func TestOutboxMigrationIsTheLibrarys(t *testing.T) {
	raw, err := fs.ReadFile(FS, "00003_antenne_outbox.sql")
	if err != nil {
		t.Fatalf("read 00003: %v", err)
	}
	if string(raw) != outbox.Migration {
		t.Fatal("00003_antenne_outbox.sql differs from outbox.Migration; copy the library's migration again")
	}
}
